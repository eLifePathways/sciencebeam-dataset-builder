"""One card per repo, generated so it cannot drift from the schema or the registry.

The card's `license` field is a discovery hint rather than the statement that counts:
the Hub takes a single identifier, so a repo holding more than one licence can only say
`other`. What may be done with a document is decided per document.
"""

from collections.abc import Mapping

import pyarrow as pa

from sciencebeam_dataset_builder.corpus.layout import Tier, config_name, data_files
from sciencebeam_dataset_builder.corpus.registry import Corpus
from sciencebeam_dataset_builder.corpus.schema import CORPUS_SCHEMA, FIELD_DESCRIPTIONS
from sciencebeam_dataset_builder.dataset.split import SPLIT_NAMES

GENERATED_MARKER = "<!-- generated by corpus.card - do not edit -->"

# Declaring the most demanding licence present is a licence-compatibility judgement and
# should be confirmed by whoever owns licence questions. `cc-by-4.0` holds only while the
# open repos are homogeneous; a CC0 or a 3.0 document arriving makes it `other`.
DECLARED_LICENCE: dict[Tier, str] = {
    Tier.OPEN: "cc-by-4.0",
    Tier.RESTRICTED: "other",
}

Counts = Mapping[str, Mapping[str, int]]


def _type_label(field_type: pa.DataType) -> str:
    if pa.types.is_boolean(field_type):
        return "bool"
    if pa.types.is_binary(field_type):
        return "binary"
    return "string"


def size_category(total: int) -> str:
    if total < 1_000:
        return "n<1K"
    if total < 10_000:
        return "1K<n<10K"
    if total < 100_000:
        return "10K<n<100K"
    return "100K<n<1M"


def render_front_matter(corpus: Corpus, tier: Tier, counts: Counts) -> str:
    total = sum(sum(splits.values()) for splits in counts.values())
    lines = [
        "---",
        f"pretty_name: {corpus.name} ({tier.value})",
        f"license: {DECLARED_LICENCE[tier]}",
        f"size_categories:\n- {size_category(total)}",
    ]
    if corpus.languages:
        lines.append("language:")
        lines.extend(f"- {code}" for code in corpus.languages)
    lines.append("configs:")
    for pairing in corpus.pairings:
        lines.append(f"- config_name: {config_name(corpus.name, pairing)}")
        lines.append("  data_files:")
        for entry in data_files(pairing):
            lines.append(f"  - {{split: {entry['split']}, path: {entry['path']}}}")
    lines.append("---")
    return "\n".join(lines)


def render_schema_table() -> str:
    lines = ["| column | type | null | description |", "| --- | --- | --- | --- |"]
    for field in CORPUS_SCHEMA:
        nullable = "yes" if field.nullable else "**no**"
        lines.append(
            f"| `{field.name}` | `{_type_label(field.type)}` | {nullable} | "
            f"{FIELD_DESCRIPTIONS.get(field.name, '')} |"
        )
    return "\n".join(lines)


def render_splits_table(counts: Counts) -> str:
    lines = [
        "| config | " + " | ".join(SPLIT_NAMES) + " | total |",
        "| --- | " + " | ".join("---:" for _ in SPLIT_NAMES) + " | ---: |",
    ]
    for pairing, splits in counts.items():
        cells = [str(splits.get(name, 0)) for name in SPLIT_NAMES]
        lines.append(
            f"| `{pairing}` | " + " | ".join(cells) + f" | {sum(splits.values())} |"
        )
    return "\n".join(lines)


def render_card(corpus: Corpus, tier: Tier, counts: Counts) -> str:
    """The whole card: generated front matter and tables, then the shared prose."""
    first_config = config_name(corpus.name, corpus.pairings[0])
    return "\n".join(
        [
            render_front_matter(corpus, tier, counts),
            "",
            GENERATED_MARKER,
            "",
            f"# {corpus.name} ({tier.value})",
            "",
            corpus.description,
            "",
            "Each row pairs a document's PDF with the publisher's JATS, for benchmarking",
            "and training PDF to XML conversion.",
            "",
            _tier_paragraph(tier),
            "",
            "## Splits",
            "",
            render_splits_table(counts),
            "",
            "`test` is a held-out benchmark set and should not be trained on. A document's",
            "split travels with it: it is the same in every repo that carries the document,",
            "and it does not change when the corpus grows or loses rows.",
            "",
            "## Schema",
            "",
            render_schema_table(),
            "",
            "## Corrections",
            "",
            "Some of the published JATS is wrong, and where we have fixed it the `xml`",
            "column carries our corrected version rather than the publisher's. Those",
            "documents are modified, which `xml_upstream_sha` identifies: it is the",
            "checksum of the XML as harvested, and `corrections/<id>/` holds that original",
            "beside the edit and the reason for it.",
            "",
            "## The corpus set is provisional",
            "",
            "The target is author manuscripts and preprints. Some corpora here are neither,",
            "corpora may be added, and corpora may be retired. A release is a git tag, so",
            "pin one with `revision=` rather than reading `main` if a number depends on it.",
            "",
            "## Loading",
            "",
            "```python",
            "from datasets import load_dataset",
            "",
            f'ds = load_dataset("{corpus.repo_id(tier)}", "{first_config}")',
            'print(ds["test"][0]["uid"])',
            "```",
            "",
        ]
    )


def _tier_paragraph(tier: Tier) -> str:
    if tier.public:
        return (
            "Every document here is openly licensed and may be redistributed with "
            "attribution. Attribution is discharged per document from the `xml`, which "
            "carries the title, the author list and the licence statement."
        )
    return (
        "This repo is private because its documents may not be redistributed. What each "
        "one permits differs, so the card declares `other` rather than a single licence."
    )
